/****************************************************************************
 * Design: Two-phase initialization
 *
 * Phase 1 - screen_manager_init() - called from main() before
 *   threads:
 *   Creates bare lv_obj_t screens (no image objects, no widgets).
 *   Loads SCREEN_SPLASH as active screen (black until phase 2).
 *   Safe because lv_obj_create(NULL) does not trigger rendering.
 *
 * Phase 2 - screen_manager_setup_assets() - called from
 *   lvgl_thread:
 *   Attaches lv_img to splash screen.
 *   Attaches lv_img to dashboard screen (theme bg + widgets).
 *   Attaches lv_img to theme screen (theme bg only, no widgets).
 *   Calls widgets_init() on dashboard screen in correct LVGL
 *   context.
 *   This is the ONLY correct place to create LVGL objects with
 *   assets.
 *
 * Asset selection is driven by Kconfig:
 *   CONFIG_HMI_SPLASH_xxx -> splash screen image
 *   CONFIG_HMI_THEME_xxx  -> dashboard + theme screen image
 *
 ****************************************************************************/

